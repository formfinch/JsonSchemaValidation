    private static IReadOnlyList<QualitySummaryEntry> BuildQualitySummary(IReadOnlyList<ReportRow> rows)
    {
        var entries = new List<QualitySummaryEntry>();
        foreach (var group in rows.GroupBy(row => row.Target, StringComparer.Ordinal).OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            var passingScenarios = 0;
            var failingScenarios = 0;
            var failingProfiles = new SortedSet<string>(StringComparer.Ordinal);

            foreach (var row in group)
            {
                var rowFailed = false;

                if (row.Status != "generated")
                {
                    rowFailed = true;
                    failingProfiles.Add($"codegen:{row.Status}");
                }

                if (row.StrictProfiles is { Count: > 0 })
                {
                    foreach (var profile in row.StrictProfiles)
                    {
                        if (profile.Value.Status == "failed")
                        {
                            rowFailed = true;
                            failingProfiles.Add(profile.Key);
                        }
                    }
                }

                if (rowFailed)
                {
                    failingScenarios++;
                }
                else
                {
                    passingScenarios++;
                }
            }

            entries.Add(new QualitySummaryEntry
            {
                Target = group.Key,
                Status = failingScenarios == 0 ? "pass" : "fail",
                PassingScenarioCount = passingScenarios,
                FailingScenarioCount = failingScenarios,
                FailingProfiles = failingProfiles.ToArray()
            });
        }

        return entries;
    }

