    private static IReadOnlyDictionary<string, BaselineRow> LoadBaseline(string baselinePath)
    {
        if (!File.Exists(baselinePath))
        {
            return new Dictionary<string, BaselineRow>(StringComparer.Ordinal);
        }

        var baseline = JsonSerializer.Deserialize<BaselineDocument>(
            File.ReadAllText(baselinePath, Utf8NoBom),
            CreateJsonOptions());
        return baseline?.Rows.ToDictionary(row => GetBaselineKey(row.Target, row.Schema), StringComparer.Ordinal)
            ?? new Dictionary<string, BaselineRow>(StringComparer.Ordinal);
    }

    private static MetricDeltas? CalculateBaselineDeltas(ReportRow row, IReadOnlyDictionary<string, BaselineRow> baseline)
    {
        if (!baseline.TryGetValue(GetBaselineKey(row.Target, row.Schema), out var baselineRow))
        {
            return null;
        }

        var statusChange = string.Equals(row.Status, baselineRow.Status, StringComparison.Ordinal)
            ? null
            : $"{baselineRow.Status} -> {row.Status}";

        return new MetricDeltas
        {
            StatusChange = statusChange,
            StrictProfileChanges = ComputeStrictProfileChanges(row.StrictProfiles, baselineRow.StrictProfiles),
            ValidatorBytes = Subtract(row.ValidatorBytes, baselineRow.ValidatorBytes),
            RuntimeBytes = Subtract(row.RuntimeBytes, baselineRow.RuntimeBytes),
            TotalBytes = Subtract(row.TotalBytes, baselineRow.TotalBytes),
            GzipBytes = Subtract(row.GzipBytes, baselineRow.GzipBytes),
            Loc = Subtract(row.Loc, baselineRow.Loc),
            FunctionCount = Subtract(row.FunctionCount, baselineRow.FunctionCount),
            MaxIndentationDepth = Subtract(row.MaxIndentationDepth, baselineRow.MaxIndentationDepth),
            HelperCount = Subtract(row.HelperCount, baselineRow.HelperCount)
        };
    }

    private static IReadOnlyList<string>? ComputeStrictProfileChanges(
        IReadOnlyDictionary<string, StrictProfileReport>? current,
        IReadOnlyDictionary<string, string>? baseline)
    {
        // Old baselines (pre-strict-profile baseline support) have null here, in which case there
        // is no flip to surface — leave the field unset rather than fabricating a "missing -> X" entry.
        if (baseline is null || baseline.Count == 0)
        {
            return null;
        }

        var changes = new List<string>();
        var profileNames = new SortedSet<string>(StringComparer.Ordinal);
        if (current is not null)
        {
            foreach (var name in current.Keys)
            {
                profileNames.Add(name);
            }
        }
        foreach (var name in baseline.Keys)
        {
            profileNames.Add(name);
        }

        foreach (var name in profileNames)
        {
            var oldStatus = baseline.TryGetValue(name, out var b) ? b : "(missing)";
            var newStatus = current is not null && current.TryGetValue(name, out var c) ? c.Status : "(missing)";
            if (!string.Equals(oldStatus, newStatus, StringComparison.Ordinal))
            {
                changes.Add($"{name}: {oldStatus} -> {newStatus}");
            }
        }

        return changes.Count == 0 ? null : changes;
    }

    private static string NormalizeSource(string source)
    {
        var normalized = source.Replace("\r\n", "\n", StringComparison.Ordinal).Replace('\r', '\n');
        return normalized.TrimEnd('\n') + "\n";
    }

    private static int CountUtf8Bytes(string source) => Utf8NoBom.GetByteCount(source);

    private static int CountPhysicalLines(string source) => source.Length == 0 ? 0 : source.Split('\n').Length - 1;

    private static int CountFunctions(string source)
    {
        return FunctionRegex().Matches(source).Count + ArrowFunctionRegex().Matches(source).Count;
    }

    private static int CalculateMaxIndentationDepth(string source)
    {
        var maxColumns = 0;
        foreach (var line in source.Split('\n'))
        {
            var columns = 0;
            foreach (var c in line)
            {
                if (c == ' ')
                {
                    columns++;
                }
                else if (c == '\t')
                {
                    columns += 4;
                }
                else
                {
                    break;
                }
            }

            maxColumns = Math.Max(maxColumns, columns);
        }

        return maxColumns / 2;
    }

    private static int CountGzipBytes(string source)
    {
        var bytes = Utf8NoBom.GetBytes(source);
        using var memoryStream = new MemoryStream();
        using (var gzipStream = new GZipStream(memoryStream, CompressionLevel.Optimal, leaveOpen: true))
        {
            gzipStream.Write(bytes, 0, bytes.Length);
        }

        return checked((int)memoryStream.Length);
    }

    private static IReadOnlyList<string> ExtractRuntimeImports(string source)
    {
        var helpers = new SortedSet<string>(StringComparer.Ordinal);
        foreach (Match match in RuntimeImportRegex().Matches(source))
        {
            var names = match.Groups["names"].Value.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
            foreach (var name in names)
            {
                var cleaned = name;
                if (cleaned.StartsWith("type ", StringComparison.Ordinal))
                {
                    // Per-specifier `type X` is a compile-time-only import; skip it.
                    continue;
                }

                var asIndex = cleaned.IndexOf(" as ", StringComparison.Ordinal);
                if (asIndex >= 0)
                {
                    cleaned = cleaned[..asIndex].Trim();
                }

                if (cleaned.Length > 0)
                {
                    helpers.Add(cleaned);
                }
            }
        }

        return helpers.ToArray();
    }

    private static string RenderConsole(ReportDocument report)
    {
        var sb = new StringBuilder();
        sb.AppendLine("Codegen Output Quality");
        sb.AppendLine("======================");
        sb.AppendLine();
        sb.AppendLine("Quality Summary");
        sb.AppendLine("---------------");
        sb.AppendLine("FAIL       = at least one scenario is rejected by codegen (e.g. unsupported), fails code generation, or fails a strictness profile.");
        sb.AppendLine("INCOMPLETE = no failures, but at least one strictness profile could not run (e.g. tsc unavailable).");
        sb.AppendLine("PASS       = every scenario compiled cleanly under every strictness profile that ran.");
        sb.AppendLine("None of these statuses imply anything about runtime validation correctness.");
        sb.AppendLine();

        var summaryHeaders = new[] { "target", "status", "pass", "fail", "incomplete", "failing strict profiles", "incomplete strict profiles" };
        var summaryRows = report.QualitySummary
            .OrderBy(entry => entry.Target, StringComparer.Ordinal)
            .Select(entry => new[]
            {
                entry.Target,
                entry.Status.ToUpperInvariant(),
                entry.PassingScenarioCount.ToString(System.Globalization.CultureInfo.InvariantCulture),
                entry.FailingScenarioCount.ToString(System.Globalization.CultureInfo.InvariantCulture),
                entry.IncompleteScenarioCount.ToString(System.Globalization.CultureInfo.InvariantCulture),
                entry.FailingProfiles.Count == 0 ? "-" : string.Join(", ", entry.FailingProfiles),
                entry.IncompleteProfiles.Count == 0 ? "-" : string.Join(", ", entry.IncompleteProfiles)
            })
            .ToArray();
        AppendPlainTable(sb, summaryHeaders, summaryRows, rightAlignColumns: [2, 3, 4]);
        sb.AppendLine();

        sb.AppendLine("Per-Schema Metrics");
        sb.AppendLine("------------------");
        var metricHeaders = new[] { "target", "schema", "status", "validator", "runtime", "total", "gzip", "loc", "fns", "depth", "helpers", "deltas" };
        var metricRows = report.Rows
            .OrderBy(row => row.Target, StringComparer.Ordinal)
            .ThenBy(row => row.Schema, StringComparer.Ordinal)
            .Select(row => new[]
            {
                row.Target,
                row.Schema,
                row.Status,
                FormatNullable(row.ValidatorBytes),
                FormatNullable(row.RuntimeBytes),
                FormatNullable(row.TotalBytes),
                FormatNullable(row.GzipBytes),
                FormatNullable(row.Loc),
                FormatNullable(row.FunctionCount),
                FormatNullable(row.MaxIndentationDepth),
                FormatNullable(row.HelperCount),
                FormatDeltas(row.BaselineDeltas)
            })
            .ToArray();
        AppendPlainTable(sb, metricHeaders, metricRows, rightAlignColumns: [3, 4, 5, 6, 7, 8, 9, 10]);
        sb.AppendLine();

        var tsRows = report.Rows
            .Where(row => row.StrictProfiles is { Count: > 0 })
            .OrderBy(row => row.Schema, StringComparer.Ordinal)
            .ToArray();
        if (tsRows.Length > 0)
        {
            sb.AppendLine("TypeScript Strictness Detail");
            sb.AppendLine("----------------------------");
            var profileNames = tsRows
                .SelectMany(row => row.StrictProfiles!.Keys)
                .Distinct(StringComparer.Ordinal)
                .OrderBy(name => name, StringComparer.Ordinal)
                .ToArray();
            var strictHeaders = new[] { "schema" }.Concat(profileNames).ToArray();
            var strictRows = tsRows.Select(row =>
            {
                var cells = new string[strictHeaders.Length];
                cells[0] = row.Schema;
                for (var i = 0; i < profileNames.Length; i++)
                {
                    cells[i + 1] = row.StrictProfiles!.TryGetValue(profileNames[i], out var profile)
                        ? profile.Status
                        : "-";
                }
                return cells;
            }).ToArray();
            AppendPlainTable(sb, strictHeaders, strictRows, rightAlignColumns: []);
            sb.AppendLine();
        }

        sb.AppendLine("Notes");
        sb.AppendLine("-----");
        foreach (var note in report.Notes)
        {
            sb.AppendLine("- " + note);
        }

        return sb.ToString();
    }

    private static void AppendPlainTable(
        StringBuilder sb,
        IReadOnlyList<string> headers,
        IReadOnlyList<string[]> rows,
        IReadOnlyList<int> rightAlignColumns)
    {
        var widths = new int[headers.Count];
        for (var i = 0; i < headers.Count; i++)
        {
            widths[i] = headers[i].Length;
        }
        foreach (var row in rows)
        {
            for (var i = 0; i < headers.Count; i++)
            {
                if (row[i].Length > widths[i])
                {
                    widths[i] = row[i].Length;
                }
            }
        }

        AppendPlainTableRow(sb, headers.ToArray(), widths, rightAlignColumns);
        var separator = new string[headers.Count];
        for (var i = 0; i < headers.Count; i++)
        {
            separator[i] = new string('-', widths[i]);
        }
        AppendPlainTableRow(sb, separator, widths, []);
        foreach (var row in rows)
        {
            AppendPlainTableRow(sb, row, widths, rightAlignColumns);
        }
    }

    private static void AppendPlainTableRow(
        StringBuilder sb,
        string[] cells,
        int[] widths,
        IReadOnlyList<int> rightAlignColumns)
    {
        for (var i = 0; i < cells.Length; i++)
        {
            if (i > 0)
            {
                sb.Append("  ");
            }
            sb.Append(rightAlignColumns.Contains(i) ? cells[i].PadLeft(widths[i]) : cells[i].PadRight(widths[i]));
        }
        sb.AppendLine();
    }

