    private static string FormatNullable(int? value) => value?.ToString(System.Globalization.CultureInfo.InvariantCulture) ?? "";

    private static string FormatDeltas(MetricDeltas? deltas)
    {
        if (deltas == null)
        {
            return "";
        }

        var hasNumericDelta = deltas.TotalBytes.HasValue || deltas.GzipBytes.HasValue || deltas.Loc.HasValue;
        var hasProfileChanges = deltas.StrictProfileChanges is { Count: > 0 };
        if (deltas.StatusChange is null && !hasNumericDelta && !hasProfileChanges)
        {
            return "";
        }

        var parts = new List<string>();
        if (deltas.StatusChange is { } statusChange)
        {
            // Highlight status flips (e.g. generated -> unsupported) since metric deltas alone
            // would not surface a regression that drops a row out of code generation.
            parts.Add($"status {statusChange}");
        }

        if (hasNumericDelta)
        {
            parts.Add($"total {FormatDelta(deltas.TotalBytes)}, gzip {FormatDelta(deltas.GzipBytes)}, loc {FormatDelta(deltas.Loc)}");
        }

        if (hasProfileChanges)
        {
            parts.Add($"strict_profiles {string.Join(", ", deltas.StrictProfileChanges!)}");
        }

        return string.Join("; ", parts);
    }

    private static string FormatDelta(int? value)
    {
        if (!value.HasValue)
        {
            return "";
        }

        return value.Value >= 0 ? "+" + value.Value.ToString(System.Globalization.CultureInfo.InvariantCulture) : value.Value.ToString(System.Globalization.CultureInfo.InvariantCulture);
    }

