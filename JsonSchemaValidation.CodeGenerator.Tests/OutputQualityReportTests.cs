    private static string FormatNullable(int? value) => value?.ToString(System.Globalization.CultureInfo.InvariantCulture) ?? "";

    private static string FormatDeltas(MetricDeltas? deltas)
    {
        if (deltas == null)
        {
            return "";
        }

        if (!deltas.TotalBytes.HasValue &&
            !deltas.GzipBytes.HasValue &&
            !deltas.Loc.HasValue)
        {
            return "";
        }

        return $"total {FormatDelta(deltas.TotalBytes)}, gzip {FormatDelta(deltas.GzipBytes)}, loc {FormatDelta(deltas.Loc)}";
    }

    private static string FormatDelta(int? value)
    {
        if (!value.HasValue)
        {
            return "";
        }

        return value.Value >= 0 ? "+" + value.Value.ToString(System.Globalization.CultureInfo.InvariantCulture) : value.Value.ToString(System.Globalization.CultureInfo.InvariantCulture);
    }

