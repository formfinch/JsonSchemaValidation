    [Trait("Category", "OutputQuality")]
    public async Task OutputQuality_GeneratesReportedOnlyJsAndTsMetrics()
    {
        if (!ShouldRunReport())
        {
            // Opt-in by design: this test runs the JS/TS code generator, executes tsc multiple times,
            // and writes report artifacts to the repo. It's not part of routine `dotnet test` runs.
            // To run it locally, follow the instructions in README.md (Local JS/TS Output Quality Report)
            // or set JSV_RUN_CODEGEN_QUALITY_REPORT=1 on the test invocation.
            _testOutput.WriteLine(
                "Codegen output quality report not generated: set JSV_RUN_CODEGEN_QUALITY_REPORT=1 to opt in.");
            return;
        }

        var repoRoot = FindRepositoryRoot();
        var reportDirectory = Path.Combine(repoRoot, "artifacts", "codegen-output-quality");
        var baselinePath = Path.Combine(repoRoot, "benchmarks", "codegen-output-quality-baseline.json");
        Directory.CreateDirectory(reportDirectory);

        var scenarios = LoadScenarios(repoRoot);
        var rows = new List<ReportRow>();
        var typeScriptRows = new List<GeneratedTargetRow>();

        foreach (var scenario in scenarios)
        {
            using var schemaDocument = JsonDocument.Parse(scenario.SchemaJson);
            var schema = schemaDocument.RootElement.Clone();

            var javaScriptRow = await GenerateTargetRowAsync(
                new JavaScriptCodeGenerationTarget(),
                new JavaScriptCodeGenerationOptions
                {
                    FormatAssertionEnabled = true,
                    ExternalSchemaDocuments = scenario.ExternalSchemaDocuments,
                    OutputHints = new CodeGenerationOutputHints { BaseFileName = scenario.Id }
                },
                schema,
                scenario.Id);
            rows.Add(javaScriptRow.Row);

            var typeScriptRow = await GenerateTargetRowAsync(
                new TypeScriptCodeGenerationTarget(),
                new TypeScriptCodeGenerationOptions
                {
                    FormatAssertionEnabled = true,
                    ExternalSchemaDocuments = scenario.ExternalSchemaDocuments,
                    OutputHints = new CodeGenerationOutputHints { BaseFileName = scenario.Id }
                },
                schema,
                scenario.Id);
            rows.Add(typeScriptRow.Row);
            if (typeScriptRow.Artifacts.Any(artifact => artifact.Role == GeneratedArtifactRole.Primary))
            {
                typeScriptRows.Add(typeScriptRow);
            }
        }

        ApplyTypeScriptStrictnessProfiles(typeScriptRows);

        var baseline = LoadBaseline(baselinePath);
        foreach (var row in rows)
        {
            row.BaselineDeltas = CalculateBaselineDeltas(row, baseline);
        }

        var qualitySummary = BuildQualitySummary(rows);

        var report = new ReportDocument
        {
            FormatVersion = 1,
            Notes =
            [
                "Reported-only output quality metrics for JavaScript and TypeScript code generation.",
                "All generated artifacts are normalized to UTF-8 text with LF line endings and one trailing newline before measurement.",
                "gzip_bytes is computed by System.IO.Compression.GZipStream with CompressionLevel.Optimal.",
                "function_count is a lightweight regex-based shape signal and can count function-like text in comments or strings.",
                "TypeScript strict_profiles compile every generated schema in one tsc invocation per profile, then attribute diagnostics back to each schema by source file. The per-profile entry under strict_profiles uses status 'failed' (with remediation 'generated-code') when the row's own .ts file has errors, status 'failed' (remediation 'runtime-types') when only the shared jsv-runtime.ts has errors, status 'unavailable' when tsc could not run, and status 'passed' otherwise. Strict-profile failures do not change the row's top-level status field, which only reflects the codegen step ('generated', 'unsupported', or 'generation-failed').",
                "quality_summary statuses: 'pass' = every scenario compiled cleanly under every strictness profile that ran. 'fail' = at least one scenario was rejected by codegen (e.g. status 'unsupported'), failed code generation, or failed a strictness profile. 'incomplete' = no failures, but at least one strictness profile could not run (e.g. tsc was not found). None of these imply anything about runtime validation correctness.",
                "baseline_deltas.status_change appears as 'old -> new' when a row's top-level status flips between baseline and current run (e.g. 'generated -> unsupported'); a flip out of 'generated' makes numeric deltas unreliable because no validator was emitted in the new run.",
                "baseline_deltas.strict_profile_changes lists per-profile status flips ('profile-name: old -> new') for TypeScript rows; the baseline file persists each profile's last status so regressions like 'no-unchecked-indexed-access: passed -> failed' surface alongside numeric deltas.",
                "Helper selection correctness is tracked separately by issue #46; this report measures footprint only.",
                "JS/TS deduplication decisions are tracked separately by issue #42.",
                "Lint/static-analysis signals are deferred to follow-up work."
            ],
            QualitySummary = qualitySummary,
            Rows = rows
        };

        var jsonOptions = CreateJsonOptions();
        var markdown = RenderMarkdown(report);
        File.WriteAllText(
            Path.Combine(reportDirectory, "codegen-output-quality.json"),
            JsonSerializer.Serialize(report, jsonOptions),
            Utf8NoBom);
        File.WriteAllText(
            Path.Combine(reportDirectory, "codegen-output-quality.md"),
            markdown,
            Utf8NoBom);

        if (ShouldPrintReport())
        {
            _testOutput.WriteLine("===== Codegen Output Quality Report =====");
            _testOutput.WriteLine(RenderConsole(report));
            _testOutput.WriteLine("===== End Report =====");
        }

        if (ShouldUpdateBaseline())
        {
            // Refuse to overwrite the baseline when any strict profile could not run (e.g. tsc was
            // unavailable). Persisting "unavailable" statuses would poison future delta comparisons
            // because the next run with tsc available would look like a regression.
            var unavailableProfiles = rows
                .Where(row => row.StrictProfiles is not null)
                .SelectMany(row => row.StrictProfiles!
                    .Where(profile => string.Equals(profile.Value.Status, "unavailable", StringComparison.Ordinal))
                    .Select(profile => $"{row.Target}/{row.Schema}:{profile.Key}"))
                .ToArray();
            if (unavailableProfiles.Length > 0)
            {
                throw new InvalidOperationException(
                    "Refusing to update the baseline because the report is incomplete. " +
                    "Strict profiles reported 'unavailable' (likely because tsc was not found). " +
                    $"Affected: {string.Join(", ", unavailableProfiles.Take(5))}{(unavailableProfiles.Length > 5 ? ", ..." : "")}. " +
                    "Install a TypeScript compiler 5.0+ and re-run with JSV_UPDATE_CODEGEN_QUALITY_BASELINE=1.");
            }

            Directory.CreateDirectory(Path.GetDirectoryName(baselinePath)!);
            var nextBaseline = BaselineDocument.FromRows(rows);
            File.WriteAllText(
                baselinePath,
                JsonSerializer.Serialize(nextBaseline, jsonOptions),
                Utf8NoBom);
        }

        var jsonReportPath = Path.Combine(reportDirectory, "codegen-output-quality.json");
        var markdownReportPath = Path.Combine(reportDirectory, "codegen-output-quality.md");
        Assert.True(File.Exists(jsonReportPath), "Expected the JSON report to be written.");
        Assert.True(File.Exists(markdownReportPath), "Expected the Markdown report to be written.");
        Assert.NotEmpty(rows);
        Assert.Contains(rows, row => row.Target == "javascript");
        Assert.Contains(rows, row => row.Target == "typescript");
        Assert.NotEmpty(qualitySummary);
        Assert.All(qualitySummary, entry =>
        {
            Assert.Contains(entry.Status, new[] { "pass", "fail", "incomplete" });
            Assert.Equal(group(rows, entry.Target),
                entry.PassingScenarioCount + entry.FailingScenarioCount + entry.IncompleteScenarioCount);
        });
        Assert.Contains("Quality Summary", markdown);
        Assert.Contains("Per-Schema Metrics", markdown);
        Assert.All(rows.Where(row => row.Target == "typescript" && row.Status == "generated"),
            row => Assert.NotNull(row.StrictProfiles));

        static int group(IReadOnlyList<ReportRow> all, string target) =>
            all.Count(row => string.Equals(row.Target, target, StringComparison.Ordinal));
    }

    private static async Task<GeneratedTargetRow> GenerateTargetRowAsync(
        ICodeGenerationTarget target,
        CodeGenerationOptions options,
        JsonElement schema,
        string scenarioId)
    {
        var request = new CodeGenerationRequest
        {
            Schema = schema,
            Options = options
        };

        var capability = await target.GetCapabilitiesAsync(request);
        if (!capability.CanGenerate)
        {
            return new GeneratedTargetRow(new ReportRow
            {
                Target = target.Descriptor.Id,
                Schema = scenarioId,
                Status = "unsupported",
                Diagnostics = MapDiagnostics(capability.Diagnostics),
                Helpers = [],
                StrictProfiles = target.Descriptor.Id == "typescript" ? new Dictionary<string, StrictProfileReport>() : null
            }, []);
        }

        var generation = await target.GenerateAsync(request);
        if (!generation.Success)
        {
            return new GeneratedTargetRow(new ReportRow
            {
                Target = target.Descriptor.Id,
                Schema = scenarioId,
                Status = "generation-failed",
                Diagnostics = MapDiagnostics(generation.Diagnostics),
                Helpers = [],
                StrictProfiles = target.Descriptor.Id == "typescript" ? new Dictionary<string, StrictProfileReport>() : null
            }, []);
        }

        var artifacts = generation.Artifacts
            .OrderByDescending(artifact => artifact.Role == GeneratedArtifactRole.Primary)
            .ThenBy(artifact => artifact.RelativePath, StringComparer.Ordinal)
            .Select(artifact => new NormalizedArtifact(
                artifact.RelativePath,
                artifact.Kind,
                artifact.Role,
                NormalizeSource(artifact.Content)))
            .ToArray();

        var primaryContent = string.Concat(artifacts
            .Where(artifact => artifact.Role == GeneratedArtifactRole.Primary)
            .Select(artifact => artifact.Content));
        var supportContent = string.Concat(artifacts
            .Where(artifact => artifact.Role != GeneratedArtifactRole.Primary)
            .Select(artifact => artifact.Content));
        var helpers = ExtractRuntimeImports(primaryContent).Order(StringComparer.Ordinal).ToArray();

        // Sum gzip-compressed sizes per artifact role rather than gzipping concatenated content,
        // because the JS/TS targets emit primary and support as separate files and that is what
        // users actually ship. Concatenated compression would benefit from cross-file dedup that
        // does not exist on disk.
        var gzipBytes = CountGzipBytes(primaryContent) + (supportContent.Length > 0 ? CountGzipBytes(supportContent) : 0);

        return new GeneratedTargetRow(new ReportRow
        {
            Target = target.Descriptor.Id,
            Schema = scenarioId,
            Status = "generated",
            Diagnostics = [],
            ValidatorBytes = CountUtf8Bytes(primaryContent),
            RuntimeBytes = CountUtf8Bytes(supportContent),
            TotalBytes = CountUtf8Bytes(primaryContent) + CountUtf8Bytes(supportContent),
            GzipBytes = gzipBytes,
            Loc = CountPhysicalLines(primaryContent),
            FunctionCount = CountFunctions(primaryContent),
            MaxIndentationDepth = CalculateMaxIndentationDepth(primaryContent),
            HelperCount = helpers.Length,
            Helpers = helpers,
            StrictProfiles = target.Descriptor.Id == "typescript" ? new Dictionary<string, StrictProfileReport>() : null
        }, artifacts);
    }

    private static void ApplyTypeScriptStrictnessProfiles(IReadOnlyList<GeneratedTargetRow> typeScriptRows)
    {
        foreach (var row in typeScriptRows)
        {
            row.Row.StrictProfiles ??= new Dictionary<string, StrictProfileReport>();
        }

        if (typeScriptRows.Count == 0)
        {
            return;
        }

        if (!TypeScriptCompiler.IsAvailable())
        {
            foreach (var row in typeScriptRows)
            {
                foreach (var profile in GetStrictnessProfiles())
                {
                    row.Row.StrictProfiles![profile.Name] = new StrictProfileReport
                    {
                        Status = "unavailable",
                        Remediation = "unknown",
                        Diagnostics = ["TypeScript compiler 'tsc' is not available."]
                    };
                }
            }
            return;
        }

        var tempRoot = Path.Combine(Path.GetTempPath(), "jsv-output-quality-ts-" + Guid.NewGuid().ToString("N"));
        var sourceRoot = Path.Combine(tempRoot, "src");
        Directory.CreateDirectory(sourceRoot);
        try
        {
            var runtimePath = Path.Combine(sourceRoot, TsRuntime.FileName);
            File.WriteAllText(runtimePath, NormalizeSource(TsRuntime.GetSource()), Utf8NoBom);

            var sourcePaths = new List<string> { runtimePath };
            var rowSourcePaths = new Dictionary<GeneratedTargetRow, string>();
            foreach (var generatedRow in typeScriptRows)
            {
                // typeScriptRows is filtered upstream to only contain rows with a primary artifact,
                // so Single() is the right invariant here.
                var primaryArtifact = generatedRow.Artifacts.Single(artifact => artifact.Role == GeneratedArtifactRole.Primary);
                var sourcePath = Path.Combine(sourceRoot, $"{generatedRow.Row.Schema}.ts");
                File.WriteAllText(sourcePath, primaryArtifact.Content, Utf8NoBom);
                sourcePaths.Add(sourcePath);
                rowSourcePaths[generatedRow] = sourcePath;
            }

            var relativeSourcePaths = sourcePaths
                .Select(path => Path.GetRelativePath(tempRoot, path))
                .ToArray();
            foreach (var profile in GetStrictnessProfiles())
            {
                var outputDirectory = Path.Combine(tempRoot, "out", profile.Name);
                var compileResult = TypeScriptCompiler.Compile(
                    relativeSourcePaths,
                    outputDirectory,
                    ecmaScriptTarget: "ES2020",
                    options: profile.Options,
                    timeoutMilliseconds: 240_000,
                    workingDirectory: tempRoot);
                var attributedDiagnostics = AttributeTscDiagnostics(compileResult, tempRoot);

                foreach (var (generatedRow, sourcePath) in rowSourcePaths)
                {
                    var rowFileName = Path.GetFileName(sourcePath);
                    var rowDiagnostics = attributedDiagnostics.GetValueOrDefault(rowFileName, []);
                    var runtimeDiagnostics = attributedDiagnostics.GetValueOrDefault(TsRuntime.FileName, []);

                    string status;
                    string? remediation;
                    if (rowDiagnostics.Count > 0)
                    {
                        status = "failed";
                        remediation = "generated-code";
                    }
                    else if (runtimeDiagnostics.Count > 0)
                    {
                        status = "failed";
                        remediation = "runtime-types";
                    }
                    else if (!compileResult.Success)
                    {
                        status = "failed";
                        remediation = "unknown";
                    }
                    else
                    {
                        status = "passed";
                        remediation = null;
                    }

                    var rowReport = new List<string>();
                    rowReport.AddRange(rowDiagnostics);
                    rowReport.AddRange(runtimeDiagnostics.Select(line => "[shared-runtime] " + line));

                    generatedRow.Row.StrictProfiles![profile.Name] = new StrictProfileReport
                    {
                        Status = status,
                        Remediation = remediation,
                        Diagnostics = TruncateDiagnostics(rowReport)
                    };
                }
            }
        }
        finally
        {
            try { Directory.Delete(tempRoot, recursive: true); } catch { /* best effort */ }
        }
    }

    private static IReadOnlyDictionary<string, IReadOnlyList<string>> AttributeTscDiagnostics(
        TypeScriptCompilationResult result,
        string tempRoot)
    {
        var attributed = new Dictionary<string, List<string>>(StringComparer.Ordinal);
        if (result.Success)
        {
            return attributed.ToDictionary(
                pair => pair.Key,
                pair => (IReadOnlyList<string>)pair.Value,
                StringComparer.Ordinal);
        }

        var rawText = string.Concat(
            string.IsNullOrWhiteSpace(result.StandardError) ? "" : result.StandardError + "\n",
            string.IsNullOrWhiteSpace(result.StandardOutput) ? "" : result.StandardOutput);
        var normalized = NormalizeDiagnosticText(rawText, tempRoot);

        string? currentFileKey = null;
        foreach (var line in normalized.Split('\n'))
        {
            var trimmed = line.TrimEnd();
            if (trimmed.Length == 0)
            {
                continue;
            }

            var match = TscDiagnosticHeaderRegex().Match(trimmed);
            if (match.Success)
            {
                var path = match.Groups["path"].Value;
                currentFileKey = Path.GetFileName(path);
            }

            if (currentFileKey is null)
            {
                continue;
            }

            if (!attributed.TryGetValue(currentFileKey, out var bucket))
            {
                bucket = new List<string>();
                attributed[currentFileKey] = bucket;
            }
            bucket.Add(trimmed);
        }

        return attributed.ToDictionary(
            pair => pair.Key,
            pair => (IReadOnlyList<string>)pair.Value,
            StringComparer.Ordinal);
    }

    private static IReadOnlyList<string> TruncateDiagnostics(IReadOnlyList<string> lines)
    {
        const int maxLines = 80;
        if (lines.Count <= maxLines)
        {
            return lines.ToArray();
        }

        return lines.Take(maxLines)
            .Append($"... truncated {lines.Count - maxLines} additional diagnostic lines")
            .ToArray();
    }

