    private static IReadOnlyList<QualitySummaryEntry> BuildQualitySummary(IReadOnlyList<ReportRow> rows)
    {
        var entries = new List<QualitySummaryEntry>();
        foreach (var group in rows.GroupBy(row => row.Target, StringComparer.Ordinal).OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            var passingScenarios = 0;
            var failingScenarios = 0;
            var incompleteScenarios = 0;
            var failingProfiles = new SortedSet<string>(StringComparer.Ordinal);
            var incompleteProfiles = new SortedSet<string>(StringComparer.Ordinal);
            var hasIncomplete = false;

            foreach (var row in group)
            {
                var rowFailed = false;
                var rowIncomplete = false;

                if (row.Status != "generated")
                {
                    rowFailed = true;
                    failingProfiles.Add($"codegen:{row.Status}");
                }

                if (row.StrictProfiles is { Count: > 0 })
                {
                    foreach (var profile in row.StrictProfiles)
                    {
                        switch (profile.Value.Status)
                        {
                            case "failed":
                                rowFailed = true;
                                failingProfiles.Add(profile.Key);
                                break;
                            case "skipped":
                                rowFailed = true;
                                failingProfiles.Add($"{profile.Key}:skipped");
                                break;
                            case "unavailable":
                                rowIncomplete = true;
                                hasIncomplete = true;
                                incompleteProfiles.Add($"{profile.Key}:tsc-unavailable");
                                break;
                        }
                    }
                }

                if (rowFailed)
                {
                    failingScenarios++;
                }
                else if (rowIncomplete)
                {
                    incompleteScenarios++;
                }
                else
                {
                    passingScenarios++;
                }
            }

            string status;
            if (failingScenarios > 0)
            {
                status = "fail";
            }
            else if (hasIncomplete)
            {
                status = "incomplete";
            }
            else
            {
                status = "pass";
            }

            entries.Add(new QualitySummaryEntry
            {
                Target = group.Key,
                Status = status,
                PassingScenarioCount = passingScenarios,
                FailingScenarioCount = failingScenarios,
                IncompleteScenarioCount = incompleteScenarios,
                FailingProfiles = failingProfiles.ToArray(),
                IncompleteProfiles = incompleteProfiles.ToArray()
            });
        }

        return entries;
    }

